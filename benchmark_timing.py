"""Measure computational cost on THIS machine and write the results table.

Run this on the machine you will name in the paper. Timings measured
elsewhere must not be reported as yours.

    python benchmark_timing.py
"""
import json, warnings
warnings.filterwarnings("ignore")

from pdpipe.timing import pin_threads
pin_threads(1)                      # before heavy imports

from pdpipe.data import load_oxford
from pdpipe.models import build_models
from pdpipe.timing import benchmark, environment_report

if __name__ == "__main__":
    cohort = load_oxford()
    table, env = benchmark(cohort, build_models(), n_repetitions=5)
    table.to_csv("results/timing.csv", index=False)
    with open("results/environment.json", "w") as f:
        json.dump(env, f, indent=2)
    print("\n=== Environment ===")
    for k, v in env.items():
        print(f"  {k}: {v}")
    print("\n=== Timings ===")
    cols = ["model", "end_to_end_tuning_s", "fit_mean_s", "fit_sd_s",
            "inference_mean_ms", "peak_rss_mb"]
    print(table[cols].to_string(index=False))

    # Emit a LaTeX block ready to paste over PLACEHOLDER-TIMING.
    with open("results/timing_table.tex", "w") as f:
        f.write("% Generated by benchmark_timing.py -- paste over PLACEHOLDER-TIMING\n")
        for _, r in table.iterrows():
            f.write(f"{r['model']} & {r['end_to_end_tuning_s']:.2f} & "
                    f"{r['fit_mean_s']:.4f} $\\pm$ {r['fit_sd_s']:.4f} & "
                    f"{r['inference_mean_ms']:.2f} & {r['peak_rss_mb']:.0f} \\\\\n")
        f.write("\\midrule\n\\multicolumn{5}{l}{\\textbf{Environment}} \\\\\n")
        f.write(f"\\multicolumn{{5}}{{l}}{{Processor: {env.get('cpu_model','n/a')}; "
                f"logical cores: {env.get('logical_cores','n/a')}; "
                f"memory: {env.get('memory_gb','n/a')} GB}} \\\\\n")
        f.write(f"\\multicolumn{{5}}{{l}}{{{env.get('platform','n/a')}; "
                f"Python {env.get('python','n/a')}}} \\\\\n")
        f.write(f"\\multicolumn{{5}}{{l}}{{scikit-learn {env.get('scikit_learn','n/a')}; "
                f"XGBoost {env.get('xgboost','n/a')}; LightGBM {env.get('lightgbm','n/a')}; "
                f"CatBoost {env.get('catboost','n/a')}}} \\\\\n")
        f.write("\\multicolumn{5}{l}{Threads pinned: 1; timing repetitions: 5; "
                "random seed: 20260917} \\\\\n")
    print("\nLaTeX block written to results/timing_table.tex")
